def conn(x, y, w, h, name, lines=(), size=11):
    out.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="2" fill="{CONN}" '
               f'stroke="#8a7a3a" stroke-width="1.1"/>')
    n = len(lines) + 1
    cy = y + h / 2 - (n - 1) * size * 0.65 + size * 0.36
    text(x + w / 2, cy, name, size, "bold")
    for s in lines:
        cy += size * 1.3
        text(x + w / 2, cy, s, size * 0.86, color=C["muted"])


def small(x, y, s, color=None, size=10, anchor="start", weight="normal"):
    text(x, y, s, size, weight, color or C["muted"], anchor)


